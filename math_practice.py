# Задание 4: нормализация вектора
# ============================================================
print("\n--- Задание 4: Нормализация вектора ---")
def normalize(v):
    norm = np.linalg.norm(v)
    if norm == 0:
        return v
    return v / norm

v = np.array([3, 4])
normalized = normalize(v)
print(f"v = {v}")
print(f"Нормализованный: {normalized}")
print(f"Длина нормализованного: {np.linalg.norm(normalized):.4f}")

