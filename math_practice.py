print("\n--- Задание 5: Косинусное сходство ---")
# Три фильма, представленные векторами признаков
# [рейтинг, длительность, бюджет]
movies = {
    "Фильм A": np.array([8.5, 120, 100]),
    "Фильм B": np.array([8.0, 130, 95]),
    "Фильм C": np.array([6.0, 90, 30]),
}

print("Векторы фильмов:")
for name, vector in movies.items():
    print(f"  {name}: {vector}")

print("\nКосинусное сходство:")
movie_names = list(movies.keys())
for i in range(len(movie_names)):
    for j in range(i + 1, len(movie_names)):
        sim = np.dot(movies[movie_names[i]], movies[movie_names[j]]) / \
              (np.linalg.norm(movies[movie_names[i]]) * np.linalg.norm(movies[movie_names[j]]))
        print(f"  {movie_names[i]} vs {movie_names[j]}: {sim:.4f}")

