# === Сравнение косинуса и евклидова расстояния ===
print("=== Косинус vs Евклидово расстояние ===")
# Два коротких документа на одну тему
doc1 = np.array([1, 0, 0])
# Длинный документ на ту же тему
doc2 = np.array([100, 0, 0])
# Документ на другую тему, но той же длины
doc3 = np.array([0, 1, 0])

print(f"\ndoc1 = {doc1}")
print(f"doc2 = {doc2} (та же тема, но 'длиннее')")
print(f"doc3 = {doc3} (другая тема, но та же 'длина')")

print(f"\nКосинусное сходство:")
print(f"  doc1 vs doc2: {cosine_similarity(doc1, doc2):.4f}")
print(f"  doc1 vs doc3: {cosine_similarity(doc1, doc3):.4f}")

print(f"\nЕвклидово расстояние:")
print(f"  doc1 vs doc2: {np.linalg.norm(doc2 - doc1):.4f}")
print(f"  doc1 vs doc3: {np.linalg.norm(doc3 - doc1):.4f}")

print("""
Вывод:
- Косинус правильно говорит: doc1 похож на doc2 (одна тема)
- Евклидово расстояние говорит: doc1 ближе к doc3 (меньше длина)

Для задач сравнения ТЕКСТОВ и ДОКУМЕНТОВ косинус лучше!
""")

