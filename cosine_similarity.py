import numpy as np

# === Косинусное сходство ===
# Формула:
# cos_sim(a, b) = dot(a, b) / (|a| * |b|)
# где |a| и |b| — длины векторов

def cosine_similarity(a, b):
    """
    Косинусное сходство между двумя векторами.
    Возвращает значение в диапазоне [-1, 1].
    1 — векторы идентичны по направлению
    0 — векторы перпендикулярны
    -1 — векторы противоположны по направлению
    """
    dot = np.dot(a, b)
    norm_a = np.linalg.norm(a)
    norm_b = np.linalg.norm(b)
    # Защита от деления на ноль
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return dot / (norm_a * norm_b)

print("=== Косинусное сходство ===")

# Пример 1: идентичные векторы
a = np.array([1, 2, 3])
b = np.array([1, 2, 3])
print(f"\nПример 1: идентичные векторы")
print(f"a = {a}")
print(f"b = {b}")
print(f"Косинусное сходство: {cosine_similarity(a, b):.4f}")

# Пример 2: векторы в одном направлении, но разной длины
a = np.array([1, 2, 3])
b = np.array([2, 4, 6])
print(f"\nПример 2: одно направление, разная длина")
print(f"a = {a}")
print(f"b = {b}")
print(f"Косинусное сходство: {cosine_similarity(a, b):.4f}")
print("→ Косинусное сходство НЕ зависит от длины вектора!")

# Пример 3: перпендикулярные векторы
a = np.array([1, 0])
b = np.array([0, 1])
print(f"\nПример 3: перпендикулярные векторы")
print(f"a = {a}")
print(f"b = {b}")
print(f"Косинусное сходство: {cosine_similarity(a, b):.4f}")

# Пример 4: противоположные векторы
a = np.array([1, 2, 3])
b = np.array([-1, -2, -3])
print(f"\nПример 4: противоположные векторы")
print(f"a = {a}")
print(f"b = {b}")
print(f"Косинусное сходство: {cosine_similarity(a, b):.4f}")

