-- День 21: WHERE vs HAVING — ключевая тема для собеседований
-- ============================================================

-- ============================================================
-- ПОРЯДОК ВЫПОЛНЕНИЯ SQL-ЗАПРОСА
-- ============================================================
--
-- SQL выполняет запрос в таком порядке:
--
--   1. FROM          (откуда брать данные)
--   2. WHERE         (фильтр строк ДО группировки)
--   3. GROUP BY      (группировка)
--   4. HAVING        (фильтр групп ПОСЛЕ группировки)
--   5. SELECT        (выбор столбцов и агрегатов)
--   6. ORDER BY      (сортировка результата)
--   7. LIMIT         (ограничение количества строк)
--
-- Это объясняет, почему:
-- - В WHERE нельзя использовать агрегаты (они ещё не вычислены)
-- - В HAVING можно использовать агрегаты (они уже вычислены)
-- - В ORDER BY можно использовать алиасы из SELECT

-- ============================================================
-- ПРИМЕР 1: WHERE фильтрует строки ДО группировки
-- ============================================================
-- Задача: средний балл по категориям, но только для дорогих товаров
SELECT
    category,
    COUNT(*) AS count,
    ROUND(AVG(price), 2) AS avg_price
FROM products
WHERE price > 100          -- сначала фильтруем строки
GROUP BY category          -- потом группируем
ORDER BY avg_price DESC;

-- ============================================================
-- ПРИМЕР 2: HAVING фильтрует группы ПОСЛЕ группировки
-- ============================================================
-- Задача: категории, где средняя цена выше 150
SELECT
    category,
    ROUND(AVG(price), 2) AS avg_price
FROM products
GROUP BY category
HAVING AVG(price) > 150    -- фильтруем уже сгруппированные данные
ORDER BY avg_price DESC;

-- ============================================================
-- ПРИМЕР 3: WHERE и HAVING вместе
-- ============================================================
-- Задача: для товаров дороже 50 найти категории,
-- где таких товаров больше 3
SELECT
    category,
    COUNT(*) AS expensive_count,
    ROUND(AVG(price), 2) AS avg_price
FROM products
WHERE price > 50                    -- 1) фильтр строк
GROUP BY category                   -- 2) группировка
HAVING COUNT(*) > 3                 -- 3) фильтр групп
ORDER BY expensive_count DESC;

-- ============================================================
-- СРАВНИТЕЛЬНАЯ ТАБЛИЦА
-- ============================================================
--
-- | Аспект               | WHERE                    | HAVING                   |
-- |----------------------|--------------------------|--------------------------|
-- | Когда применяется    | ДО группировки           | ПОСЛЕ группировки        |
-- | К чему применяется   | К отдельным строкам      | К группам строк          |
-- | Агрегатные функции   | ❌ Нельзя использовать   | ✅ Можно использовать    |
-- | Обязательность       | GROUP BY не нужен        | Требует GROUP BY         |
-- | Алиасы из SELECT     | ❌ Нельзя                | ✅ В PostgreSQL можно    |
-- | Скорость             | Быстрее (фильтр раньше)  | Медленнее                |
--
-- ============================================================
-- ПРАВИЛО ВЫБОРА
-- ============================================================
--
-- Если условие касается ОТДЕЛЬНОЙ строки → WHERE
--   Пример: "цена > 100", "категория = 'Электроника'"
--
-- Если условие касается ГРУППЫ строк → HAVING
--   Пример: "средняя цена > 150", "количество > 5"

-- ============================================================
-- ТИПИЧНАЯ ОШИБКА НА СОБЕСЕДОВАНИИ
-- ============================================================

-- НЕПРАВИЛЬНО: агрегат в WHERE
-- SELECT category, AVG(price)
-- FROM products
-- WHERE AVG(price) > 150     -- ОШИБКА!
-- GROUP BY category;

-- ПРАВИЛЬНО: агрегат в HAVING
SELECT category, ROUND(AVG(price), 2) AS avg_price
FROM products
GROUP BY category
HAVING AVG(price) > 150;