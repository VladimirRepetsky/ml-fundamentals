"""
Применение SVD: снижение размерности и сжатие данных.
"""
import numpy as np

print("=" * 60)
print("  СНИЖЕНИЕ РАЗМЕРНОСТИ ЧЕРЕЗ SVD")
print("=" * 60)

# === Исходные данные ===
# Матрица «пользователи × фильмы» с оценками
# Классический пример из рекомендательных систем
ratings = np.array([
    [5, 5, 0, 0, 0],   # Пользователь 1: любит фильмы 1 и 2
    [5, 4, 0, 0, 0],   # Пользователь 2: похожие вкусы
    [0, 0, 5, 5, 0],   # Пользователь 3: любит фильмы 3 и 4
    [0, 0, 4, 5, 0],   # Пользователь 4: похожие вкусы
    [0, 0, 0, 0, 5],   # Пользователь 5: любит только фильм 5
])

print("\nМатрица оценок (пользователи × фильмы):")
print(ratings)
print("Форма:", ratings.shape)

# === SVD ===
U, s, Vt = np.linalg.svd(ratings, full_matrices=False)

print("\nСингулярные числа:", s.round(4))
print("Количество:", len(s))

# === Доля объяснённой дисперсии ===
total = np.sum(s ** 2)
print("\nДоля объяснённой дисперсии:")
cumulative = 0
for i, sv in enumerate(s):
    energy = sv ** 2 / total * 100
    cumulative += energy
    print(f"  Компонента {i+1}: {energy:.1f}% (накопительно: {cumulative:.1f}%)")

# === Сжатие: оставляем только топ-k компонент ===
print("\n" + "=" * 60)
print("  СЖАТИЕ ДАННЫХ")
print("=" * 60)

def compress_svd(matrix, k):
    """
    Сжимает матрицу, оставляя только топ-k сингулярных чисел.
    """
    U, s, Vt = np.linalg.svd(matrix, full_matrices=False)
    
    # Оставляем только k компонент
    U_k = U[:, :k]
    s_k = s[:k]
    Vt_k = Vt[:k, :]
    
    # Восстанавливаем приближённую матрицу
    Sigma_k = np.diag(s_k)
    compressed = U_k @ Sigma_k @ Vt_k
    
    # Считаем, сколько информации сохранилось
    total_energy = np.sum(s ** 2)
    kept_energy = np.sum(s_k ** 2)
    info_kept = kept_energy / total_energy * 100
    
    return compressed, info_kept

# Сжимаем с разным количеством компонент
print("\nСжатие матрицы оценок:")
for k in range(1, len(s) + 1):
    compressed, info = compress_svd(ratings, k)
    print(f"  k={k}: сохранено {info:.1f}% информации")

# === Практический пример: сжатие с 2 компонентами ===
print("\n" + "=" * 60)
print("  ПРИМЕР: СЖАТИЕ С 2 КОМПОНЕНТАМИ")
print("=" * 60)

compressed_2, info_2 = compress_svd(ratings, 2)
print(f"\nОригинальная матрица:")
print(ratings)
print(f"\nСжатая матрица (k=2), сохранено {info_2:.1f}% информации:")
print(compressed_2.round(2))

print("\n=== Интерпретация ===")
print("Обрати внимание:")
print("- Пользователи 1 и 2 похожи (оба любят фильмы 1, 2)")
print("- Пользователи 3 и 4 похожи (оба любят фильмы 3, 4)")
print("- SVD выявляет эти скрытые группы (латентные факторы)")

