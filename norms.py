import numpy as np

# === Основные нормы вектора ===

def l1_norm(v):
    """L1-норма: сумма модулей элементов (манхэттенское расстояние)."""
    return np.sum(np.abs(v))

def l2_norm(v):
    """L2-норма: евклидова длина (обычная длина вектора)."""
    return np.sqrt(np.sum(v ** 2))

def linf_norm(v):
    """L∞-норма: максимум модуля элементов."""
    return np.max(np.abs(v))

# Тестовый вектор
v = np.array([3, -4, 0, 5])
print("Вектор:", v)

print("\n=== Нормы вектора ===")
print(f"L1-норма (сумма модулей):  {l1_norm(v)}")
print(f"L2-норма (евклидова длина): {l2_norm(v):.4f}")
print(f"L∞-норма (максимум модуля): {linf_norm(v)}")

# === Встроенные функции NumPy ===
print("\n=== Встроенные функции NumPy ===")
print(f"np.linalg.norm(v, 1):   {np.linalg.norm(v, 1)}")    # L1
print(f"np.linalg.norm(v):      {np.linalg.norm(v):.4f}")    # L2 (по умолчанию)
print(f"np.linalg.norm(v, 2):   {np.linalg.norm(v, 2):.4f}") # L2
print(f"np.linalg.norm(v, np.inf): {np.linalg.norm(v, np.inf)}")  # L∞

# === Сравнение норм на примере ===
print("\n=== Сравнение норм ===")
a = np.array([1, 1, 1, 1, 1])   # равномерное распределение
b = np.array([5, 0, 0, 0, 0])   # сосредоточенное распределение

print(f"\nВектор a (равномерный): {a}")
print(f"  L1: {l1_norm(a)}")
print(f"  L2: {l2_norm(a):.4f}")
print(f"  L∞: {linf_norm(a)}")

print(f"\nВектор b (сосредоточенный): {b}")
print(f"  L1: {l1_norm(b)}")
print(f"  L2: {l2_norm(b):.4f}")
print(f"  L∞: {linf_norm(b)}")

print("\nL1-нормы одинаковые, но L2 и L∞ разные.")
print("Это показывает, что разные нормы 'видят' вектор по-разному.")

# === Применение в машинном обучении ===
