import numpy as np

# === Геометрическое определение скалярного произведения ===
# dot(a, b) = |a| * |b| * cos(θ)
# где:
#   |a| и |b| — длины векторов
#   θ — угол между векторами

def vector_length(v):
    """Длина вектора (евклидова норма)."""
    return np.sqrt(np.sum(v ** 2))

def angle_between_vectors(a, b):
    """Угол между векторами в радианах."""
    dot = np.dot(a, b)
    len_a = vector_length(a)
    len_b = vector_length(b)
    # Защита от деления на ноль и числовых погрешностей
    cos_angle = np.clip(dot / (len_a * len_b), -1.0, 1.0)
    return np.arccos(cos_angle)

print("=== Геометрический смысл скалярного произведения ===")

# Пример 1: векторы под прямым углом
a = np.array([1, 0])
b = np.array([0, 1])
print(f"\nПример 1: перпендикулярные векторы")
print(f"a = {a}, b = {b}")
print(f"Угол: {np.degrees(angle_between_vectors(a, b)):.1f}°")
print(f"Скалярное произведение: {np.dot(a, b)}")
print("→ Если угол 90°, скалярное произведение = 0")

# Пример 2: векторы в одном направлении
a = np.array([1, 0])
b = np.array([2, 0])
print(f"\nПример 2: векторы в одном направлении")
print(f"a = {a}, b = {b}")
print(f"Угол: {np.degrees(angle_between_vectors(a, b)):.1f}°")
print(f"Скалярное произведение: {np.dot(a, b)}")
print("→ Если угол 0°, скалярное произведение максимально")

# Пример 3: векторы в противоположных направлениях
a = np.array([1, 0])
b = np.array([-2, 0])
print(f"\nПример 3: векторы в противоположных направлениях")
print(f"a = {a}, b = {b}")
print(f"Угол: {np.degrees(angle_between_vectors(a, b)):.1f}°")
print(f"Скалярное произведение: {np.dot(a, b)}")
print("→ Если угол 180°, скалярное произведение минимально")

# Пример 4: острый угол
a = np.array([1, 0])
b = np.array([1, 1])
angle = angle_between_vectors(a, b)
print(f"\nПример 4: острый угол")
print(f"a = {a}, b = {b}")
print(f"Угол: {np.degrees(angle):.1f}°")
print(f"Скалярное произведение: {np.dot(a, b)}")

# Пример 5: тупой угол
a = np.array([1, 0])
b = np.array([-1, 1])
angle = angle_between_vectors(a, b)
print(f"\nПример 5: тупой угол")
print(f"a = {a}, b = {b}")
print(f"Угол: {np.degrees(angle):.1f}°")
print(f"Скалярное произведение: {np.dot(a, b)}")

