# Распаковка: присваиваем элементы кортежа переменным
point = (10, 20)
x, y = point

print("x =", x)
print("y =", y)

# Обмен значениями двух переменных через кортеж
a = 5
b = 10
print("До обмена: a =", a, ", b =", b)

a, b = b, a
print("После обмена: a =", a, ", b =", b)

# Кортеж из трёх элементов
rgb = (255, 128, 0)
red, green, blue = rgb
print(f"Красный: {red}, Зелёный: {green}, Синий: {blue}")