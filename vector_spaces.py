# === Нормализация вектора ===
print("=== Нормализация вектора (приведение к единичной длине) ===")

def normalize_vector(v):
    """Нормализует вектор до единичной длины."""
    norm = np.linalg.norm(v)
    if norm == 0:
        return v
    return v / norm

v = np.array([3, 4])
normalized = normalize_vector(v)
print(f"\nИсходный вектор: {v}")
print(f"Его длина: {np.linalg.norm(v)}")
print(f"Нормализованный: {normalized}")
print(f"Длина нормализованного: {np.linalg.norm(normalized):.4f}")
print("\nЭто важно для косинусного сходства!")