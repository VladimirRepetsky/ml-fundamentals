"""
Практические упражнения по Pandas.
"""
import pandas as pd

# Загружаем данные
df = pd.read_csv("data/students.csv")

print("=" * 55)
print("Практические упражнения по Pandas")
print("=" * 55)

# ============================================================
# Упражнение 1: Базовый анализ
# ============================================================

print("\n--- Упражнение 1: Базовый анализ ---")
print("Количество студентов:", len(df))
print("Средний возраст:", df["age"].mean())
print("Средний балл:", df["score"].mean())
print("Медианный балл:", df["score"].median())
print("Максимальный балл:", df["score"].max())
print("Минимальный балл:", df["score"].min())

# ============================================================
# Упражнение 2: Фильтрация
# ============================================================

print("\n--- Упражнение 2: Фильтрация ---")

# Студенты старше 25
older = df[df["age"] > 25]
print(f"Студентов старше 25: {len(older)}")

# Студенты с баллом выше среднего
above_average = df[df["score"] > df["score"].mean()]
print(f"Студентов с баллом выше среднего: {len(above_average)}")

# Студенты, которые прошли курс
passed = df[df["passed"] == True]
print(f"Студентов, прошедших курс: {len(passed)}")

# ============================================================
# Упражнение 3: Агрегации по группам
# ============================================================

print("\n--- Упражнение 3: Агрегации по группам ---")

# Средний балл по курсам
print("Средний балл по курсам:")
print(df.groupby("course")["score"].mean().round(2))

# Средний балл по полу
print("\nСредний балл по полу:")
print(df.groupby("gender")["score"].mean().round(2))

# Средний возраст по курсам
print("\nСредний возраст по курсам:")
print(df.groupby("course")["age"].mean().round(2))

# ============================================================
# Упражнение 4: Топ и антирейтинг
# ============================================================

print("\n--- Упражнение 4: Топ и антирейтинг ---")

print("Топ-3 по баллу:")
print(df.nlargest(3, "score")[["name", "score"]])

print("\nАнтирейтинг (3 худших):")
print(df.nsmallest(3, "score")[["name", "score"]])

# ============================================================
# Упражнение 5: Сводная таблица
# ============================================================

print("\n--- Упражнение 5: Сводная таблица ---")

pivot = df.pivot_table(
    values="score",
    index="course",
    columns="gender",
    aggfunc="mean"
).round(2)

print("Средний балл по курсам и полу:")
print(pivot)

# ============================================================
# Упражнение 6: Создание признаков
# ============================================================

print("\n--- Упражнение 6: Создание признаков ---")

df["score_category"] = pd.cut(
    df["score"],
    bins=[0, 60, 70, 80, 90, 100],
    labels=["F", "D", "C", "B", "A"]
)

print("Распределение по категориям:")
print(df["score_category"].value_counts())

print("\nСтуденты по категориям:")
print(df[["name", "score", "score_category"]])

# ============================================================
# Итоги
# ============================================================

print("\n" + "=" * 55)
print("Все упражнения выполнены!")
print("=" * 55)