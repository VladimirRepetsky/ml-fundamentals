def normalize_features(X):
    """
    Нормализует признаки в диапазон [0, 1].
    
    Формула: (x - min) / (max - min)
    
    Параметры:
        X: матрица признаков (n_samples, n_features)
    
    Возвращает:
        Нормализованная матрица
    """
    X_min = np.min(X, axis=0)
    X_max = np.max(X, axis=0)
    
    # Защита от деления на ноль (если признак константный)
    range_ = X_max - X_min
    range_[range_ == 0] = 1
    
    return (X - X_min) / range_


def standardize_features(X):
    """
    Стандартизирует признаки (среднее 0, стд 1).
    
    Формула: (x - mean) / std
    
    Параметры:
        X: матрица признаков (n_samples, n_features)
    
    Возвращает:
        Стандартизированная матрица
    """
    X_mean = np.mean(X, axis=0)
    X_std = np.std(X, axis=0)
    
    # Защита от деления на ноль
    X_std[X_std == 0] = 1
    
    return (X - X_mean) / X_std


def euclidean_distance(a, b):
    """
    Вычисляет евклидово расстояние между двумя векторами.
    
    Формула: sqrt(sum((a - b)^2))
    
    Это основа алгоритма KNN.
    """
    return np.sqrt(np.sum((a - b) ** 2))


def compute_distance_matrix(X):
    """
    Вычисляет матрицу расстояний между всеми парами образцов.
    
    Параметры:
        X: матрица признаков (n_samples, n_features)
    
    Возвращает:
        Матрица расстояний (n_samples, n_samples)
    """
    n = X.shape[0]
    distances = np.zeros((n, n))
    
    for i in range(n):
        for j in range(n):
            distances[i, j] = euclidean_distance(X[i], X[j])
    
    return distances


