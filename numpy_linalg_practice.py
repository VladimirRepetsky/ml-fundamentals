# Данные о 6 домах:
# - площадь (кв. м)
# - количество комнат
# - возраст дома (лет)
# - цена (тысячи)

data = np.array([
    [50, 2, 10, 150],
    [70, 3, 5, 200],
    [90, 3, 15, 250],
    [120, 4, 3, 350],
    [60, 2, 20, 140],
    [80, 3, 8, 220],
])

feature_names = ["площадь", "комнаты", "возраст", "цена"]

print("=" * 60)
print("  МИНИ-ПРОЕКТ: ЛИНЕЙНАЯ АЛГЕБРА НА ДАННЫХ")
print("=" * 60)

# ============================================================
# ЧАСТЬ 1: Представление данных
# ============================================================

print("\n--- ЧАСТЬ 1: Представление данных ---")
print("Исходные данные:")
print(data)
print("Форма:", data.shape)
print("Признаки:", feature_names)

# ============================================================
# ЧАСТЬ 2: Транспонирование
# ============================================================

print("\n--- ЧАСТЬ 2: Транспонирование ---")
transposed = data.T
print("Транспонированная матрица:")
print(transposed)
print("Форма:", transposed.shape)

# ============================================================
# ЧАСТЬ 3: Агрегации по осям
# ============================================================

print("\n--- ЧАСТЬ 3: Агрегации ---")

print("Среднее по каждому признаку:")
means = np.mean(data, axis=0)
for name, value in zip(feature_names, means):
    print(f"  {name}: {value:.2f}")

print("\nСтандартное отклонение по каждому признаку:")
stds = np.std(data, axis=0)
for name, value in zip(feature_names, stds):
    print(f"  {name}: {value:.2f}")

print("\nМинимум и максимум по каждому признаку:")
mins = np.min(data, axis=0)
maxs = np.max(data, axis=0)
for name, mn, mx in zip(feature_names, mins, maxs):
    print(f"  {name}: min={mn}, max={mx}")

# ============================================================
# ЧАСТЬ 4: Матрица признаков и целевая переменная
# ============================================================

print("\n--- ЧАСТЬ 4: Матрица признаков и целевая переменная ---")

# Признаки — все столбцы кроме последнего (цены)
X = data[:, :-1]
# Целевая переменная — последний столбец (цена)
y = data[:, -1]

print("Матрица признаков X:")
print(X)
print("Форма X:", X.shape)

print("\nЦелевая переменная y (цена):")
print(y)
print("Форма y:", y.shape)

# ============================================================
# ЧАСТЬ 5: Нормализация и стандартизация
# ============================================================

print("\n--- ЧАСТЬ 5: Нормализация ---")
X_normalized = normalize_features(X)
print("Нормализованная матрица признаков:")
print(np.round(X_normalized, 3))

print("\n--- ЧАСТЬ 5: Стандартизация ---")
X_standardized = standardize_features(X)
print("Стандартизированная матрица признаков:")
print(np.round(X_standardized, 3))

# ============================================================
# ЧАСТЬ 6: Матричное умножение
# ============================================================

print("\n--- ЧАСТЬ 6: Матричное умножение ---")

# X.T @ X — это ключевая операция в линейной регрессии
XtX = X.T @ X
print("X.T @ X:")
print(XtX)
print("Форма:", XtX.shape)

# X @ X.T
XXt = X @ X.T
print("\nX @ X.T:")
print(XXt)
print("Форма:", XXt.shape)

# ============================================================
# ЧАСТЬ 7: Евклидово расстояние
# ============================================================

print("\n--- ЧАСТЬ 7: Евклидово расстояние ---")

# Расстояние между первым и вторым домом (по нормализованным признакам)
dist = euclidean_distance(X_normalized[0], X_normalized[1])
print(f"Расстояние между домом 1 и домом 2: {dist:.4f}")

# Матрица расстояний
print("\nМатрица расстояний между всеми домами:")
dist_matrix = compute_distance_matrix(X_normalized)
print(np.round(dist_matrix, 3))

# Найти ближайшего соседа для первого дома
print("\nБлижайший сосед для дома 1:")
distances_from_first = dist_matrix[0]
# Исключаем сам дом (расстояние 0)
distances_from_first_copy = distances_from_first.copy()
distances_from_first_copy[0] = np.inf
nearest_index = np.argmin(distances_from_first_copy)
print(f"  Индекс: {nearest_index + 1}")
print(f"  Расстояние: {distances_from_first_copy[nearest_index]:.4f}")

# ============================================================
# ЧАСТЬ 8: Симуляция предсказания линейной регрессии
# ============================================================

print("\n--- ЧАСТЬ 8: Симуляция линейной регрессии ---")
print("Формула: y_pred = X @ w + b")
print("Это то, что ты будешь реализовывать в проекте Недели 10!")

# Допустим, мы нашли такие веса (в реальности их находит модель)
w = np.array([2.0, 30.0, -1.0])
b = 10.0

y_pred = X @ w + b

print("\nВеса:", w)
print("Смещение (bias):", b)
print("\nПредсказанные цены:", y_pred)
print("Реальные цены:     ", y)

