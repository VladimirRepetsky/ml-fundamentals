# Упражнение 1
arr = create_array()
print(f"\n1. Массив от 1 до 20: {arr}")

# Упражнение 2
data = np.array([12, -7, 5, 64, -1, 0, 33, 8])
print(f"\n2. Фильтрация:")
print(f"   Исходный: {data}")
print(f"   Чётные: {filter_even(data)}")
print(f"   Положительные: {filter_positive(data)}")
print(f"   Между 0 и 30: {filter_range(data, 0, 30)}")

# Упражнение 3
print(f"\n3. Статистики:")
stats = get_statistics(data)
for key, value in stats.items():
    print(f"   {key}: {value:.2f}")

# Упражнение 4
print(f"\n4. Преобразование:")
original = np.array([10, 20, 30, 40, 50])
normalized = normalize(original)
standardized = standardize(original)
print(f"   Исходный: {original}")
print(f"   Нормализованный: {normalized}")
print(f"   Стандартизированный: {standardized}")
print(f"   Среднее нормализованного: {np.mean(normalized):.2f}")
print(f"   Среднее стандартизированного: {np.mean(standardized):.2f}")
print(f"   Стд. отклонение стандартизированного: {np.std(standardized):.2f}")

# Упражнение 5
print(f"\n5. Евклидово расстояние:")
point_a = np.array([1, 2, 3])
point_b = np.array([4, 6, 3])
distance = euclidean_distance(point_a, point_b)
print(f"   Точка A: {point_a}")
print(f"   Точка B: {point_b}")
print(f"   Расстояние: {distance:.2f}")

