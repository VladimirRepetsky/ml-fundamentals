"""
Практические упражнения по NumPy.
"""
import numpy as np


# ============================================================
# Упражнение 1: Создание и базовые операции
# ============================================================

def create_array():
    """Создать массив из чисел от 1 до 20 и вернуть его."""
    return np.arange(1, 21)


# ============================================================
# Упражнение 2: Фильтрация
# ============================================================

def filter_even(arr):
    """Вернуть только чётные элементы массива."""
    return arr[arr % 2 == 0]


def filter_positive(arr):
    """Вернуть только положительные элементы массива."""
    return arr[arr > 0]


def filter_range(arr, low, high):
    """Вернуть элементы в диапазоне [low, high]."""
    return arr[(arr >= low) & (arr <= high)]


# ============================================================
# Упражнение 3: Агрегации
# ============================================================

def get_statistics(arr):
    """Вернуть словарь со статистиками массива."""
    return {
        "sum": np.sum(arr),
        "mean": np.mean(arr),
        "max": np.max(arr),
        "min": np.min(arr),
        "std": np.std(arr),
        "median": np.median(arr),
    }


# ============================================================
# Упражнение 4: Преобразование
# ============================================================

def normalize(arr):
    """
    Нормализовать массив в диапазон [0, 1].
    Формула: (x - min) / (max - min)
    
    Это важный приём в предобработке данных для ML!
    """
    return (arr - np.min(arr)) / (np.max(arr) - np.min(arr))


def standardize(arr):
    """
    Стандартизировать массив (среднее 0, стд. отклонение 1).
    Формула: (x - mean) / std
    
    Ещё один важный приём в предобработке данных для ML!
    """
    return (arr - np.mean(arr)) / np.std(arr)


# ============================================================
# Упражнение 5: Евклидово расстояние
# ============================================================

def euclidean_distance(a, b):
    """
    Вычислить евклидово расстояние между двумя векторами.
    Формула: sqrt(sum((a - b)^2))
    
    Это основа алгоритма KNN, который ты будешь реализовывать
    в проекте Недели 10!
    """
    return np.sqrt(np.sum((a - b) ** 2))


